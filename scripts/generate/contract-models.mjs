import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(process.cwd());
const source = JSON.parse(await readFile(resolve(root, "contracts/openapi/openapi.json"), "utf8"));
const readSchema = async (name) =>
  JSON.parse(await readFile(resolve(root, `contracts/schemas/${name}.schema.json`), "utf8"));
const [jobSchema, resultSchema, manifestSchema, versionErrorSchema] = await Promise.all([
  readSchema("job-envelope"),
  readSchema("result-envelope"),
  readSchema("import-manifest"),
  readSchema("version-error"),
]);
const schemaVersion = jobSchema.properties.schema_version.const;
if (
  resultSchema.properties.schema_version.const !== schemaVersion ||
  manifestSchema.properties.schema_version.const !== schemaVersion ||
  versionErrorSchema.properties.code.const !== "ATLAS_UNKNOWN_SCHEMA_VERSION"
) {
  throw new Error("contract schema versions or stable error code are inconsistent");
}
const assertSchemaShape = (schema, name, properties, required) => {
  const actualProperties = Object.keys(schema.properties ?? {});
  const actualRequired = schema.required ?? [];
  if (
    JSON.stringify(actualProperties) !== JSON.stringify(properties) ||
    JSON.stringify(actualRequired) !== JSON.stringify(required)
  ) {
    throw new Error(`${name} schema changed without updating the generator template`);
  }
};
assertSchemaShape(
  jobSchema,
  "job-envelope",
  ["kind", "schema_version", "idempotency_key", "input_snapshot_ids", "payload"],
  ["kind", "schema_version", "idempotency_key", "input_snapshot_ids", "payload"],
);
assertSchemaShape(
  resultSchema,
  "result-envelope",
  [
    "job_id",
    "schema_version",
    "status",
    "input_snapshot_ids",
    "data_quality",
    "engine_version",
    "output",
  ],
  [
    "job_id",
    "schema_version",
    "status",
    "input_snapshot_ids",
    "data_quality",
    "engine_version",
    "output",
  ],
);
assertSchemaShape(
  manifestSchema,
  "import-manifest",
  ["schema_version", "source_name", "content_sha256", "object_key", "columns", "row_count"],
  ["schema_version", "source_name", "content_sha256", "object_key", "columns", "row_count"],
);
if (
  jobSchema.properties.input_snapshot_ids.uniqueItems !== true ||
  jobSchema.properties.input_snapshot_ids.items.minLength !== 1 ||
  resultSchema.properties.input_snapshot_ids.uniqueItems !== true ||
  resultSchema.properties.input_snapshot_ids.items.minLength !== 1 ||
  JSON.stringify(versionErrorSchema.properties.details.properties.supported_versions.const) !==
    JSON.stringify([schemaVersion])
) {
  throw new Error("generator template does not preserve schema collection constraints");
}
const header = "// Code generated by scripts/generate/contract-models.mjs; DO NOT EDIT.\n";
const pythonHeader = "# Code generated by scripts/generate/contract-models.mjs; DO NOT EDIT.\n";

const write = async (relativePath, contents) => {
  const target = resolve(root, relativePath);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, contents, "utf8");
};

