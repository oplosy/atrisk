const python = `${pythonHeader}from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

SUPPORTED_SCHEMA_VERSION = "${schemaVersion}"
UNKNOWN_SCHEMA_VERSION_CODE = "ATLAS_UNKNOWN_SCHEMA_VERSION"


class ContractModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class ErrorEnvelope(ContractModel):
    code: str = Field(pattern=r"^[A-Z][A-Z0-9_.-]+$")
    message: str = Field(min_length=1)
    request_id: str = Field(min_length=1, max_length=128)
    details: dict[str, Any] | None = None


class PageMeta(ContractModel):
    limit: int = Field(ge=1, le=200)
    next_cursor: str | None = Field(default=None, min_length=1)
    has_more: bool


class JobEnvelope(ContractModel):
    kind: str = Field(pattern=r"^[a-z][a-z0-9_.-]*$")
    schema_version: Literal["${schemaVersion}"]
    idempotency_key: str = Field(min_length=1, max_length=255)
    input_snapshot_ids: list[str] = Field(min_length=0)
    payload: dict[str, Any]

    @field_validator("input_snapshot_ids")
    @classmethod
    def snapshot_ids_are_unique(cls, value: list[str]) -> list[str]:
        if any(not snapshot_id for snapshot_id in value):
            raise ValueError("input_snapshot_ids entries must not be empty")
        if len(value) != len(set(value)):
            raise ValueError("input_snapshot_ids must contain unique values")
        return value


class ResultEnvelope(ContractModel):
    job_id: str = Field(min_length=1)
    schema_version: Literal["${schemaVersion}"]
    status: Literal["succeeded", "degraded", "blocked", "failed"]
    input_snapshot_ids: list[str] = Field(min_length=0)
    data_quality: Literal["healthy", "degraded", "blocked"]
    engine_version: str = Field(min_length=1)
    output: dict[str, Any]

    @field_validator("input_snapshot_ids")
    @classmethod
    def snapshot_ids_are_unique(cls, value: list[str]) -> list[str]:
        if any(not snapshot_id for snapshot_id in value):
            raise ValueError("input_snapshot_ids entries must not be empty")
        if len(value) != len(set(value)):
            raise ValueError("input_snapshot_ids must contain unique values")
        return value


class ImportColumn(ContractModel):
    name: str = Field(min_length=1)
    data_type: Literal["string", "decimal", "date", "datetime"]


class ImportManifest(ContractModel):
    schema_version: Literal["${schemaVersion}"]
    source_name: str = Field(min_length=1)
    content_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    object_key: str = Field(min_length=1)
    columns: list[ImportColumn] = Field(min_length=1)
    row_count: int = Field(ge=0)


class UnknownSchemaVersionDetails(ContractModel):
    kind: str = Field(min_length=1)
    schema_version: str = Field(min_length=1)
    supported_versions: list[Literal["${schemaVersion}"]] = Field(
        min_length=1, max_length=1
    )
`;

